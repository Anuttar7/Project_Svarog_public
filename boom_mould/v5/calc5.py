"""Svarog boom mould v5: v4 closed three-piece tool plus a floating 0.5 mm aluminium liner.

Builds on calc4.py (imports its geometry; v4 numbers are not repeated here). Pure stdlib.
Run it; it writes calc5_output.txt beside itself. Coordinates as calc4: x = 0 boom centreline,
y = 0 web root, z along the boom from one end, all mm, MPa, N.
Folds in review-v5-adversarial.md (findings 1-8).

Tags: [src] read from a named source, [der] derived here, [assume] a choice made here.
"""
from __future__ import annotations

import contextlib
import io
import math
import os
import sys

OUT = os.path.dirname(os.path.realpath(__file__))
sys.path.insert(0, OUT)
sys.path.append(os.path.join(OUT, os.pardir, "v4"))  # the fork keeps calc4.py in ../v4
with contextlib.redirect_stdout(io.StringIO()):
    import calc4  # noqa: E402  (v4 geometry; calc4 rewrites its own output file, unchanged)

V4 = calc4.GEOM
R_TOOL = V4["R"]          # tool face radius the laminate sees, v4 [src calc4]
G = V4["G"]               # half web gap at the tool face, v4 [src calc4]

# ---- liner ----
T_LINER = 0.5      # why fixed: the 1050A sheet already asked of Sahil on 2 Nov is 0.5 mm [src brief3]
E_AL = 69000.0     # why fixed: Young's modulus of 1050A [src EN 485-2 / handbook]
RP_H14 = 85.0      # why fixed: EN 485-2 minimum 0.2 % proof stress, 1050A-H14 [src]
RP_H14_TYP = 120.0  # why fixed: typical proof stress, 1050A-H14, used for springback [assume]
RP_O_TYP = 30.0    # why fixed: typical 1050A-O proof stress, shown for comparison only [assume]
RP_5754 = 130.0    # why fixed: EN 485-2 minimum proof stress, 5754-H22, the fallback sheet [src]
CTE_AL = 23.6e-6   # why fixed: 1050A, 20-100 C, research-v4-autoclave.md section 4 [src]
CTE_PLY = 6.1e-6   # why fixed: plywood in-plane, research-v4-autoclave.md section 4 (indicative) [src]
CURES_C = (130.0, 150.0)  # why fixed: wood ceiling in research-v4, and the v4 upper case (review v5 #8) [src]
ROOM_C = 20.0      # why fixed: lay-up temperature, as calc4 [src calc4]
MU = (0.1, 0.15, 0.3)  # why fixed: released / worn release / dry; to be replaced by the 130 C pull test [assume]
P_VAC = 0.09       # why fixed: real vacuum under a bag, not a perfect 0.1 (review v5 #2) [src review-v5]
P_BAG = (0.4, 0.8)  # why fixed: 3 and 7 bar gauge plus vacuum (calc4 section 5) [src calc4]
P_WEB = (1.44, 2.88)  # why fixed: block closing pressure on the web lands at 3 and 7 bar (review v4 HIGH 3) [src review-v4]
LIP_K = 0.42       # why fixed: cantilever-lip end-gap coefficient from review v5 #2 [src review-v5]
T_TOL = 0.04       # why fixed: plausible thickness tolerance on 0.5 mm sheet; measure each sheet [assume]
SPREAD_MAX = 0.02  # why fixed: reject a liner whose 3 micrometer readings differ by more (review v5 #5) [src review-v5]
WEB_LAND = 13.0    # why fixed: liner must run >= 3 mm past the 10 mm laminate web end (review v5 #7) [src review-v5]
LINER_STOP = 0.5   # why fixed: liner ends this far above the bleed gallery so it cannot block it [assume]
RETURN = 6.0       # why fixed: return flange down the block's outer face, where the screws go (review v5 #6) [der]
TIP_LAND = V4["TIP_LAND"]
L = V4["L"]
PIN_SLOT_Z = 150.0  # why fixed: outer screws 150 mm either side of the centre pin, 45 mm inside each tool end [assume]
BISECT_N = 80      # why fixed: bisection iterations, converges far past 0.01 mm

lines: list[str] = []


def out(s: str = "") -> None:
    lines.append(s)


def springback_ratio(r_die: float, sy: float) -> float:
    """Free radius / die radius after forming a sheet of thickness T_LINER over r_die (elastic-plastic beam)."""
    x = r_die * sy / (E_AL * T_LINER)
    return 1.0 / (4 * x**3 - 3 * x + 1)  # why fixed: the cubic of the elastic-plastic springback relation (Hosford and Caddell), not a setting


def former_radius(target: float, sy: float) -> float:
    """Die radius that springs back to target (bisection)."""
    lo, hi = 1.0, target
    for _ in range(BISECT_N):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if mid * springback_ratio(mid, sy) < target else (lo, mid)
    return (lo + hi) / 2


out("SVAROG BOOM MOULD v5: v4 tool + floating 0.5 mm aluminium liner")
out("generated by svarog-mould/calc5.py; v4 geometry imported from calc4.py; review-v5-adversarial.md folded in")
out()

# 1. geometry
R_WOOD = R_TOOL - T_LINER
x_land_wood = -(G + T_LINER)
x_butt = x_land_wood - V4["RELIEF"]
gal_y = -WEB_LAND
y_bot = V4["Y_BOT"]
bolt_y = (gal_y - V4["GALLERY"] + y_bot) / 2
out("## 1. Geometry: the liner sits between wood and laminate, so the wood moves back by its thickness")
out(f"  tool face (liner outer surface)  R{R_TOOL:.1f}, web land x = -{G:.2f}, tip land y = {R_TOOL:.1f}  (unchanged from v4) [src calc4]")
out(f"  wood arc                          R{R_WOOD:.1f}, same centre ({-(G + R_TOOL):.2f}, 0) [der]")
out(f"  wood web land                     x = {x_land_wood:.2f}, y from {gal_y:.0f} to 0 (v4: 10 tall) [der]")
out(f"  wood tip land                     y = {R_TOOL - T_LINER:.1f} [der]")
out(f"  butt faces (relieved 0.5)         x = {x_butt:.2f}  (v4: -0.70) [der]")
out(f"  bleed gallery                     y = {gal_y:.0f} to {gal_y - V4['GALLERY']:.0f} (v4: -10 to -11) [der]")
out(f"  M6 cross bolts                    y = {bolt_y:.1f} (v4: {V4['BOLT_Y']:.1f}), still in solid butt zone [der]")
out(f"  prepreg web plies cut to {V4['WEB']:.0f} mm; liner runs {WEB_LAND - LINER_STOP - V4['WEB']:.1f} mm past their end [der]")
out("  coupon blocks, tool face -> wood arc:")
for rc in V4["COUPON_R"]:
    out(f"    R{rc:.1f} -> wood R{rc - T_LINER:.1f}")
out("    plus one bare R18.0 pair (no liner) in the same cure: the liner stays on the long tool only if")
out("    the lined coupon matches the bare one in radius, angle and surface (review v5 #4) [der]")
arc_mid = (R_WOOD + T_LINER / 2) * math.pi / 2
land = WEB_LAND - LINER_STOP
dev = land + arc_mid + TIP_LAND + RETURN
out(f"  liner flat blank: web land {land:.1f} + arc {arc_mid:.2f} (mid-thickness) + tip land {TIP_LAND:.1f} "
    f"+ return flange {RETURN:.0f} = {dev:.1f} wide x {L:.0f} long, two per tool [der]")
out()

# 2. forming
out("## 2. Forming: pre-form over a former, then fit cold (review v5 #1, #2)")
k_o = springback_ratio(R_WOOD, RP_O_TYP)
k_h = springback_ratio(R_WOOD, RP_H14_TYP)
out(f"  formed over the wood R{R_WOOD:.1f} itself: O springs to R{R_WOOD * k_o:.1f}, H14 to R{R_WOOD * k_h:.1f} [der]")
dkap = 1 / R_WOOD - 1 / (R_WOOD * k_h)
m_close = E_AL * T_LINER**3 / 12 * dkap  # why fixed: 1/12 is the second moment of area of a unit-width plate, t^3/12, not a setting
out(f"  moment to hold H14 at R{R_WOOD:.1f} from that: {m_close:.2f} N mm/mm, about its full plastic moment [der]")
out("  a lifted lip closes only over lambda = sqrt(2m/p); the gap left at its end is ~0.42 dkappa lambda^2:")
for p in (P_VAC,) + P_BAG:
    lam = math.sqrt(2 * m_close / p)
    gap = LIP_K * dkap * lam**2
    out(f"    {p:.2f} MPa: lip {lam:4.1f} mm, end gap {gap:.2f} mm [der]")
out("  So the bag cannot be trusted to seat it. Pre-form instead:")
for sy in (RP_H14, RP_H14_TYP):
    rf = former_radius(R_WOOD, sy)
    out(f"    H14 at proof {sy:.0f} MPa: form over R{rf:.1f} to spring back to R{R_WOOD:.1f} "
        f"(outer-fibre strain {T_LINER / 2 / rf * 100:.1f} %) [der]")
out("  Proof stress varies by coil, so: CNC one R14.8 former from ply offcut, form, check on the block,")
out("  open by hand if tight. Accept when a 0.1 mm feeler will not enter anywhere along the arc. [der]")
out()

# 3. thermal and friction
out("## 3. Thermal: the liner floats on one pin and must slide every cycle without yielding")
w_web, w_rest = land, arc_mid + TIP_LAND
for cure in CURES_C:
    dt = cure - ROOM_C
    mis = (CTE_AL - CTE_PLY) * dt * L
    out(f"  {cure:.0f} C cure: liner grows {mis:.2f} mm more than the ply over {L:.0f}; outer screws move "
        f"{(CTE_AL - CTE_PLY) * dt * PIN_SLOT_Z:.2f} mm (3 mm slots) [der]")
out("  Friction collected over half the length (195 mm), summed across the developed width, against the force")
out("  that yields the whole section. The web strip sees block pressure, the rest sees bag pressure. [der]")
out(f"  {'gauge':>6} {'mu':>5} {'friction N':>11} {'1050A-H14 N':>12} {'':>7} {'5754-H22 N':>7}  web strip alone, N/mm vs H14 42.5")
y14 = RP_H14 * T_LINER * (w_web + w_rest)
y57 = RP_5754 * T_LINER * (w_web + w_rest)
for (pb, pw, bar) in zip(P_BAG, P_WEB, ("3 bar", "7 bar")):
    for mu in MU:
        f = mu * (pw * w_web + pb * w_rest) * L / 2
        strip = mu * pw * L / 2
        out(f"  {bar:>6} {mu:5.2f} {f:11.0f} {y14:12.0f} {'slides' if f < y14 else 'YIELDS':>7} {y57:7.0f} "
            f"{'slides' if f < y57 else 'YIELDS':>7}  {strip:5.1f}")
out("  Reading: released, the section slides at 3 and 7 bar; the web strip alone is marginal at 7 bar,")
out("  so put FEP film (0.05) under the liner on the web lands only. Dry, it yields: release is not optional.")
out("  Before fitting the long liner, pull a 20 mm strip out from between two released, sealed ply faces")
out("  under a known load at 130 C and read mu. If mu > 0.15, use 5754-H22 0.5 mm instead of 1050A. [der]")
out("  Cooldown under pressure reverses the slip: the stress goes from +f to -f. That range of 2f stays")
out("  elastic while f is below yield, which is the same test as the table (shakedown). [der]")
out()

# 4. tolerances
out("## 4. What the liner does to the numbers that matter")
out(f"  sheet thickness +-{T_TOL}: tool radius +-{T_TOL / R_TOOL * 100:.1f} % against a spring-in bracket of +-13 %: noise [der]")
out(f"  web gap: +-{T_TOL} on each web land is +-{2 * T_TOL:.2f} on 0.40. Micrometer each liner at 3 points along")
out(f"  its length, reject a spread above {SPREAD_MAX}, and set the 0.36 stops between liner faces from the readings [der]")
out("  tool-part friction: an aluminium face grows 0.23 % more than the laminate over the cure (review v5 #4).")
out("  Whether that changes spring-in or waviness on a 0.2 mm part is not known; the bare coupon answers it. [der]")
out()

# 5. fixing
out("## 5. Fixing: nothing on the forming faces, nothing under the plug")
out(f"  {RETURN:.0f} mm return flange bent down the outer face of each block at the tip-land edge (bend R1)")
out("  pan-head M3 x 12 wood screws through the flange, 3 mm below the tip land, under the bag only:")
out(f"    round hole at z = {L / 2:.0f} (the pin), 3 mm slots at z = {L / 2 - PIN_SLOT_Z:.0f} and {L / 2 + PIN_SLOT_Z:.0f} [der]")
out("  web-land edge free, 0.5 above the gallery; FEP under the liner on the web lands; Frekote both faces elsewhere [der]")
out("  the 0.36 stops and the sealant dam sit beyond the trim lines, inside the 390 liner [der]")

text = "\n".join(lines) + "\n"
with open(os.path.join(OUT, "calc5_output.txt"), "w") as fh:
    fh.write(text)
print(text)

GEOM5 = dict(V4, R_WOOD=R_WOOD, T_LINER=T_LINER, X_LAND_WOOD=x_land_wood, X_BUTT=x_butt, WEB_LAND=WEB_LAND,
             BOLT_Y5=bolt_y, LINER_STOP=LINER_STOP, RETURN=RETURN, BLANK_W=dev,
             PIN_SLOT_Z=PIN_SLOT_Z, FORMER_R=round(former_radius(R_WOOD, RP_H14_TYP), 1))
