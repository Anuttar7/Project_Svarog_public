"""Svarog boom mould v4: closed three-piece tool (two lower V clamps + silicone top plug).

Supersedes calc3.py for the tool geometry. Pure stdlib. Run it; it writes calc4_output.txt
beside itself. Coordinates: x = 0 is the boom centreline, y = 0 is the web root (where both
flange arcs are tangent to the web), all mm. The left block is drawn; the right one mirrors it.

Tags: [src] read from a named source, [der] derived here, [assume] a choice made here.
"""
from __future__ import annotations

import math
import os

OUT = os.path.dirname(os.path.realpath(__file__))

# ---- part (Boom-Facts.md section 2, Aditya's STEP) ----
R_PART_INNER = 15.0   # why fixed: cured flange inner radius from the CAD [src]
ARC_PART_DEG = 90.0   # why fixed: cured flange swept angle from the CAD [src]
T_LAM = 0.2           # why fixed: cured laminate per flange from the CAD [src]
WEB = 10.0            # why fixed: web length from the CAD [src]

# ---- spring-in: Leclerc et al. 2017 section 3 (mould R12.7 -> cured R10.6) and Leclerc, Pedivellano &
# Pellegrino 2018 (AIAA 2018-0690) section II (part designed r 12.5, cured r 10.6, 90 -> 105 deg) ----
# Same process as ours: two bolted Al mandrels, silicone V plug, bag round all, autoclave.
LECLERC_TOOL_R = 12.7    # why fixed: their mould radius, quoted in Leclerc 2017 section 3 [src]
LECLERC_CURED_R = 10.6   # why fixed: their measured cured flange radius [src]
LECLERC_TOOL_DEG = 90.0  # why fixed: their nominal flange angle [src]
LECLERC_CURED_DEG = 105.0  # why fixed: their measured cured flange angle [src]
RADFORD_SPRING_IN = 0.0116  # why fixed: calc3.py's Radford estimate at a 150 C cure, the low bound [src calc3]

# ---- tool choices ----
SLOT = 0.36       # why fixed: over-crush stop BELOW the 0.40 cured web, at the trim ends only, so the web carries the clamp (review v4 blocker 1) [src review-v4]
BUTT_RELIEF = 0.5  # why fixed: each butt face set back so the web lands are the only contact between the blocks [src review-v4]
COUPON_R = (15.2, 16.5, 18.0, 19.6)  # why fixed: Radford low bound, midpoint, Leclerc ratio, constant-curvature-change bound from review v4 [src review-v4]
TORQUE_NM = 2.0   # why fixed: M6 torque for ~1.5 kN per bolt (T = 0.2 F d), 2 MPa on the web from 5 bolts; set from the coupons [der]
GALLERY = 1.0     # why fixed: 1 x 1 mm bleed gallery at the slot foot, from the 2 Nov review [src review]
TIP_LAND = 12.0   # why fixed: flat seat for the plug and the trim margin beyond the arc [assume]
PLY_ONE = 35.0  # why fixed: phenolic birch ply is sold at 35 mm; one sheet covers the 30 mm block width with machining allowance [assume]
PLY = 18.0        # why fixed: phenolic birch ply sheet thickness the team already planned [src brief3]
N_LAM = 3         # why fixed: three vertical laminations per block (see section 4 of the output) [assume]
PLUG_OVER = 10.0  # why fixed: silicone thickness above the tip lands, enough to spread bag load [assume]
L_TOOL = 390.0    # why fixed: 360 mm part plus 15 mm trim each end, unchanged from v3 [src brief3]
BOLT_N = 5        # why fixed: cross-bolt count unchanged from v3 [src brief3]
P_AUTOCLAVE_BAR = (3.0, 7.0)  # why fixed: typical autoclave gauge range named in the task [src task]
SILICONE_CTE = 300e-6  # why fixed: typical cured RTV silicone linear CTE, research-v4-autoclave.md [src]
AL_CTE = 23e-6         # why fixed: aluminium linear CTE [src]
CURE_C = (120.0, 150.0, 180.0)  # why fixed: plausible cure range carried from calc3 [src calc3]
ROOM_C = 20.0          # why fixed: lay-up temperature [assume]
MIN_PLUG_GAP = 0.5     # why fixed: narrowest gap cast silicone reliably fills [assume]

lines: list[str] = []
def out(s: str = "") -> None:
    lines.append(s)


def tool_for(ratio_r: float, ratio_deg: float) -> tuple[float, float]:
    """Tool face radius and swept angle that cure to the part, for a measured cured/tool ratio."""
    return R_PART_INNER / ratio_r, ARC_PART_DEG / ratio_deg


out("SVAROG BOOM MOULD v4: CLOSED THREE-PIECE TOOL (2 lower V clamps + silicone top plug)")
out("generated by svarog-mould/calc4.py; supersedes calc3.py tool geometry")
out()
out("## 1. Spring-in: calc3 had the sign backwards")
r_ratio = LECLERC_CURED_R / LECLERC_TOOL_R
d_ratio = LECLERC_CURED_DEG / LECLERC_TOOL_DEG
out(f"Leclerc et al. 2017 (mould radius) and 2018 (cured shape) [src]: tool R{LECLERC_TOOL_R} at {LECLERC_TOOL_DEG:.0f} deg cured to "
    f"R{LECLERC_CURED_R} at {LECLERC_CURED_DEG:.0f} deg")
out(f"  cured/tool radius = {r_ratio:.4f}  (repo Sizing Script.py carries 0.835: the same number) [der]")
out(f"  cured/tool angle  = {d_ratio:.4f}: the flange CLOSES, the radius SHRINKS [der]")
arc_t = LECLERC_TOOL_R * math.radians(LECLERC_TOOL_DEG)
arc_c = LECLERC_CURED_R * math.radians(LECLERC_CURED_DEG)
out(f"  arc length tool {arc_t:.2f} -> cured {arc_c:.2f} mm ({(arc_c/arc_t-1)*100:+.1f}%): fibres hold it [der]")
out("calc3 said spring-in makes the cured radius LARGER and cut R14.83. Measured on this exact")
out("process it goes the other way. A tool at R14.83 would cure to about R12.4: 17% undersize.")
hi_r, hi_deg = tool_for(r_ratio, d_ratio)
lo_r = R_PART_INNER * (1 + RADFORD_SPRING_IN)
out(f"tool face if we spring in like Leclerc (ultra-thin UD, 0.05-0.07 mm): R{hi_r:.2f}, "
    f"part trimmed at {hi_deg:.1f} deg of arc [der]")
out(f"tool face if we spring in like Radford predicts for a thicker laminate: R{lo_r:.2f} [der]")
out("Our 0.2 mm woven flange sits between the two. Nobody has measured it.")
out("CUT ORDER: a convex corner of larger radius lies wholly outside a smaller one with the same")
out("tangent point (checked on 400k points, review v4). But if the curvature CHANGE is constant the tool")
out(f"needs R19.6, above R18. So tomorrow: cure coupon pairs at {COUPON_R} and only ROUGH the long blocks;")
out("finish their arc after the coupons are read, after the bake (rough, bake to constant mass, finish, seal).")
out()

R = round(hi_r, 1)  # the radius cut tomorrow
G = T_LAM  # web lands 0.40 apart = two cured flanges; the stop is separate and thinner
out(f"## 2. Lower block section (left; right mirrors), tool face R{R}")
out(f"  web land        x = -{G:.2f}, y from -{WEB:.0f} to 0 (web 0.40; a {SLOT} mm over-crush stop at each trim end only) [der]")
out(f"  arc             centre ({-(G+R):.2f}, 0), R{R}, from ({-G:.2f}, 0) to ({-(G+R):.2f}, {R:.1f}) [der]")
out(f"  tip land        y = {R:.1f}, x from {-(G+R):.2f} to {-(G+R+TIP_LAND):.2f} [der]")
blk_w = R + TIP_LAND  # block spans x = -G to -(G + R + TIP_LAND)
blk_h = N_LAM * PLY
y_bot = R - blk_h
out(f"  bleed gallery   {GALLERY:.0f} x {GALLERY:.0f} mm at y = -{WEB:.0f} [src review]")
out(f"  butt zone       y from {-(WEB+GALLERY):.0f} to {y_bot:.0f}, faces at x = -{G + BUTT_RELIEF:.2f}, FEP-taped, set back {BUTT_RELIEF} each side so only the web lands touch [der]")
out(f"  block           {L_TOOL:.0f} long x {blk_w:.2f} wide x {blk_h:.0f} tall [der]")
bolt_y = (-(WEB + GALLERY) + y_bot) / 2
out(f"  M6 cross bolts  {BOLT_N} off at y = {bolt_y:.1f}, pitch {(L_TOOL - 2*15)/(BOLT_N-1):.0f}; 2 reamed 6 mm dowels [der]")
out()
out("## 3. Where the silicone plug reaches, and the merge point")
h_min = math.sqrt(R**2 - (R - (MIN_PLUG_GAP/2 + T_LAM - G))**2) if MIN_PLUG_GAP/2 + T_LAM > G else 0.0
for h in (1.0, 2.0, h_min, 5.0, 10.0):  # why fixed: unit conversion or a design value stated in the output text beside it [der]
    gap = 2 * (G + R - math.sqrt(R**2 - h**2) - T_LAM)
    out(f"  {h:5.2f} mm above the web root: gap between the two laminates {gap:.2f} mm")
out(f"  silicone fills down to ~{h_min:.1f} mm above the root (gap >= {MIN_PLUG_GAP} mm) [der]")
out("  Below that, down to the root, neither tool fully reaches: the flanges only touch at y = 0. Cast")
out("  the plug over a measured 0.22-0.25 mm spacer so, pressurised, it extrudes into this zone; cut and")
out("  section the first coupon there before trusting it (review v4 blocker 2). A rigid wood top piece")
tongue_h = math.sqrt(R**2 - (R - (1.5 + T_LAM - G))**2)  # why fixed: unit conversion or a design value stated in the output text beside it [der]
out(f"  with a 3 mm tongue tip would stop at {tongue_h:.1f} mm: worse, and it bottoms out. [der]")
out()
out("## 4. Blanks: no glueline may cross a forming face")
out(f"  above y = 0 the block is R = {R} tall, so a horizontal glueline anywhere in 0..{R} cuts the arc.")
out(f"  Best: ONE strip of {PLY_ONE:.0f} mm phenolic birch per block, sheet parallel to the web land, ripped")
out(f"  {blk_h + 6:.0f} tall: no glueline at all, machined to {blk_w:.1f} wide. [assume, review v4 HIGH]")
trim_x = G + R - R * math.cos(math.radians(hi_deg))
out(f"  Fallback 2 x {PLY:.0f} mm the same way: one glueline at x = -{G+PLY:.2f}, beyond the part's trim")
out(f"  line (arc ends in the part at x = -{trim_x:.1f}); glue with an epoxy whose post-cured Tg is above")
out("  the cure temperature. A PVA or PU wood glue creeps at 120 C and the joint will move. [der]")
out("  Keep one phenolic film face as the web land.")
out()
out("## 5. Pressure in the autoclave")
plug_w = 2 * blk_w
side_h = blk_h - R  # plug pressure on the arc pushes the blocks apart over its projected height R (review v4)
for p in P_AUTOCLAVE_BAR:
    p_mpa = (p + 1.0) / 10.0  # gauge + 1 bar vacuum, bar -> MPa  why fixed: unit conversion or a design value stated in the output text beside it [der]
    lateral = p_mpa * side_h * L_TOOL / 1000  # why fixed: unit conversion or a design value stated in the output text beside it [der]
    web_p = lateral * 1000 / (WEB * L_TOOL)  # why fixed: unit conversion or a design value stated in the output text beside it [der]
    out(f"  {p:.0f} bar gauge + vacuum = {p_mpa:.2f} MPa on the bag:")
    out(f"    plug: ~{p_mpa:.2f} MPa normal to every laminate face it touches, root walls included [der]")
    out(f"    blocks' outer faces push them together with {lateral:.1f} kN, i.e. {web_p:.1f} MPa on the web")
    out(f"    if the shims are not bearing (net area ratio {side_h/WEB:.1f}: outer face {blk_h:.0f} less the plug push {R:.0f}; base friction lowers it further) [der]")
out("  So, as Caltech does, the bolts CLAMP: {n} x M6 at {t:.0f} N m (~1.5 kN each, ~2 MPa on the web),".format(n=BOLT_N, t=TORQUE_NM))
out("  set from the coupons. The butt faces are relieved so the web lands are the only contact,")
out("  and the {s} mm stops sit at the trim ends, in line with the web, so they cannot tip the blocks.".format(s=SLOT))
out("  The autoclave adds the load above on top of the bolts, which also covers bolt relaxation in hot wood.")
out()
out("## 6. Silicone plug growth at cure (free surface under the bag)")
for c in CURE_C:
    dt = c - ROOM_C
    grow_l = SILICONE_CTE * dt * L_TOOL
    spine_l = AL_CTE * dt * L_TOOL
    out(f"  {c:.0f} C: unrestrained plug grows {grow_l:.1f} mm over {L_TOOL:.0f}; an Al spine grows {spine_l:.1f} [der]")
out("  An unrestrained plug sliding 7-20 mm along a wet layup can drag the plies. Cast an aluminium")
out("  flat bar into the plug's top as a spine, drilled so the silicone locks through it (tin-cure")
out("  silicone does not bond to bare Al). NO FEP sheet across the V: it bridges the cusp like the bag did;")
out("  silicone releases from epoxy on its own. Use FEP only on the tip lands.")
out()
out("## 7. Sizes")
out(f"  plug: {L_TOOL:.0f} x {plug_w:.1f} wide, top {PLUG_OVER:.0f} mm above the tip lands, i.e. y = {R + PLUG_OVER:.1f} [der]")
v_plug = (plug_w * (R + PLUG_OVER) - 2 * (R * (G + R) - math.pi * R**2 / 4 + TIP_LAND * R)) * L_TOOL / 1000  # why fixed: unit conversion or a design value stated in the output text beside it [der]
out(f"  plug volume about {v_plug/1000:.2f} litre -> {v_plug*1.1/1000:.2f} kg of silicone at SG 1.1 [der]")

text = "\n".join(lines) + "\n"
with open(os.path.join(OUT, "calc4_output.txt"), "w") as f:
    f.write(text)
print(text)

GEOM = dict(R=R, G=G, WEB=WEB, GALLERY=GALLERY, TIP_LAND=TIP_LAND, BLK_W=blk_w, BLK_H=blk_h,
            Y_BOT=y_bot, BOLT_Y=bolt_y, PLY=PLY, T_LAM=T_LAM, L=L_TOOL, PLUG_OVER=PLUG_OVER,
            PLUG_W=plug_w, TRIM_DEG=hi_deg, R_LOW=lo_r, H_PLUG_MIN=h_min, BOLT_N=BOLT_N, RELIEF=BUTT_RELIEF, STOP=SLOT, COUPON_R=COUPON_R, TORQUE=TORQUE_NM)
